let currentLang = localStorage.getItem('food-lang') || 'ru';

function t(key) {
  return translations[currentLang]?.[key] || translations.ru[key] || key;
}

function getItemTitle(item) {
  if (currentLang === 'ru') return item.title;
  return itemTranslations[item.id]?.[currentLang] || item.title;
}

function getAddonTitle(addon) {
  if (addon.titleKey) return t(addon.titleKey);
  return addon.title || '';
}

function getCategoryName(cat) {
  return t(`cat.${cat.id}`);
}

function formatItemPrice(item) {
  const price = `${item.price} ₽`;
  return item.priceFrom ? `${t('price.from')} ${price}` : price;
}

function formatItemWeight(weight) {
  const num = weight.replace(/\D/g, '');
  return `/ ${num} ${t('delivery.grams')}`;
}

function applyTranslations() {
  document.documentElement.lang = currentLang;
  document.title = t('page.title');

  document.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });

  document.querySelectorAll('[data-i18n-html]').forEach((el) => {
    el.innerHTML = t(el.dataset.i18nHtml);
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });

  document.querySelectorAll('[data-i18n-aria]').forEach((el) => {
    el.setAttribute('aria-label', t(el.dataset.i18nAria));
  });

  updateLangSelects();
}

const langOptions = [
  { code: 'ru', label: 'Русский', short: 'RU' },
  { code: 'en', label: 'English', short: 'EN' },
  { code: 'uz', label: "O'zbek", short: 'UZ' },
];

function getLangOption(code) {
  return langOptions.find((opt) => opt.code === code) || langOptions[0];
}

function closeAllLangSelects() {
  document.querySelectorAll('.lang-select.open').forEach((select) => {
    select.classList.remove('open');
    select.querySelector('.lang-select__trigger')?.setAttribute('aria-expanded', 'false');
    resetLangDropdownPosition(select);
  });
}

function resetLangDropdownPosition(select) {
  const dropdown = select.querySelector('.lang-select__dropdown');
  if (!dropdown) return;

  dropdown.style.position = '';
  dropdown.style.top = '';
  dropdown.style.left = '';
  dropdown.style.right = '';
  dropdown.style.width = '';
  dropdown.style.minWidth = '';
  dropdown.style.transform = '';
}

function positionLangDropdown(select) {
  const dropdown = select.querySelector('.lang-select__dropdown');
  const trigger = select.querySelector('.lang-select__trigger');
  if (!dropdown || !trigger) return;

  if (!window.matchMedia('(max-width: 992px)').matches) {
    resetLangDropdownPosition(select);
    return;
  }

  const rect = trigger.getBoundingClientRect();
  const minWidth = 160;
  const dropdownWidth = Math.max(rect.width, minWidth);
  let left = rect.right - dropdownWidth;

  left = Math.max(8, Math.min(left, window.innerWidth - dropdownWidth - 8));

  dropdown.style.position = 'fixed';
  dropdown.style.top = `${rect.bottom + 6}px`;
  dropdown.style.left = `${left}px`;
  dropdown.style.right = 'auto';
  dropdown.style.width = `${dropdownWidth}px`;
  dropdown.style.minWidth = `${minWidth}px`;
  dropdown.style.transform = 'translateY(0)';
}

function updateLangSelects() {
  document.querySelectorAll('.lang-select').forEach((select) => {
    const current = getLangOption(currentLang);
    const valueEl = select.querySelector('.lang-select__value');
    const labelEl = select.querySelector('.lang-select__label');

    if (valueEl) valueEl.textContent = current.short;
    if (labelEl) labelEl.textContent = current.label;

    select.querySelectorAll('.lang-select__option').forEach((option) => {
      const isActive = option.dataset.lang === currentLang;
      option.classList.toggle('active', isActive);
      option.setAttribute('aria-selected', isActive ? 'true' : 'false');
    });
  });
}

function buildLangSelect(variant) {
  const current = getLangOption(currentLang);
  const select = document.createElement('div');
  select.className = `lang-select lang-select--${variant}`;

  select.innerHTML = `
    <button type="button" class="lang-select__trigger" aria-haspopup="listbox" aria-expanded="false">
      <span class="lang-select__value">${current.short}</span>
      <span class="lang-select__label">${current.label}</span>
      <svg class="lang-select__arrow" width="12" height="12" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2">
        <path d="M6 9l6 6 6-6"/>
      </svg>
    </button>
    <ul class="lang-select__dropdown" role="listbox">
      ${langOptions
        .map(
          (opt) => `
        <li>
          <button
            type="button"
            class="lang-select__option${opt.code === currentLang ? ' active' : ''}"
            data-lang="${opt.code}"
            role="option"
            aria-selected="${opt.code === currentLang ? 'true' : 'false'}"
          >
            <span class="lang-select__option-code">${opt.short}</span>
            <span class="lang-select__option-label">${opt.label}</span>
          </button>
        </li>
      `
        )
        .join('')}
    </ul>
  `;

  const trigger = select.querySelector('.lang-select__trigger');

  trigger.addEventListener('click', (e) => {
    e.stopPropagation();
    const isOpen = select.classList.contains('open');
    closeAllLangSelects();
    if (!isOpen) {
      select.classList.add('open');
      trigger.setAttribute('aria-expanded', 'true');
      positionLangDropdown(select);
    }
  });

  select.querySelectorAll('.lang-select__option').forEach((option) => {
    option.addEventListener('click', (e) => {
      e.stopPropagation();
      setLanguage(option.dataset.lang);
      closeAllLangSelects();
    });
  });

  return select;
}

function setLanguage(lang) {
  if (!translations[lang]) return;
  currentLang = lang;
  localStorage.setItem('food-lang', lang);
  applyTranslations();
  document.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang } }));
}

function initLanguageSwitcher() {
  document.querySelectorAll('[data-lang-select]').forEach((placeholder) => {
    const variant = placeholder.dataset.langSelect;
    placeholder.replaceWith(buildLangSelect(variant));
  });

  document.addEventListener('click', closeAllLangSelects);

  window.addEventListener('resize', () => {
    document.querySelectorAll('.lang-select.open').forEach((select) => {
      positionLangDropdown(select);
    });
  });

  document.addEventListener('keydown', (e) => {
    if (e.key === 'Escape') closeAllLangSelects();
  });
}

document.addEventListener('DOMContentLoaded', () => {
  initLanguageSwitcher();
  applyTranslations();
});

